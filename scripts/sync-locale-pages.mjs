#!/usr/bin/env node
/**
 * Generate thin `src/pages/it/**` re-export shells for in-scope i18n routes.
 * Source of truth is the root `src/pages/` tree (default locale EN).
 * Do not hand-edit files under `src/pages/it/` — re-run this script instead.
 *
 * Allowlist: add/remove/rename paths here when root pages change, then run
 * `npm run sync:locale-pages` (also hooked from predev via --skip-wipe mode).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pagesDir = path.join(root, "src", "pages");
const itDir = path.join(pagesDir, "it");

/** Relative to src/pages/ — default-locale implementations to mirror under it/. */
const ALLOWLIST = [
	"index.astro",
	"404.astro",
	"training.astro",
	"tours/index.astro",
	"tours/[slug].astro",
	"books/[slug].astro",
];

function relImport(fromFile, toFile) {
	const fromDir = path.dirname(fromFile);
	let rel = path.relative(fromDir, toFile).replaceAll("\\", "/");
	if (!rel.startsWith(".")) rel = `./${rel}`;
	return rel;
}

function stubContents(importPath) {
	return `---
// generated by sync-locale-pages — do not edit; update root page + allowlist
import Page from "${importPath}";
---
<Page />
`;
}

function ensureDir(dir) {
	fs.mkdirSync(dir, { recursive: true });
}

function listGeneratedAstro(dir, acc = []) {
	if (!fs.existsSync(dir)) return acc;
	for (const name of fs.readdirSync(dir)) {
		const full = path.join(dir, name);
		const st = fs.statSync(full);
		if (st.isDirectory()) listGeneratedAstro(full, acc);
		else if (name.endsWith(".astro")) acc.push(full);
	}
	return acc;
}

ensureDir(itDir);

const written = new Set();

for (const rel of ALLOWLIST) {
	const source = path.join(pagesDir, rel);
	if (!fs.existsSync(source)) {
		console.error(`sync-locale-pages: missing root page ${rel}`);
		process.exit(1);
	}
	const dest = path.join(itDir, rel);
	ensureDir(path.dirname(dest));
	const importPath = relImport(dest, source);
	fs.writeFileSync(dest, stubContents(importPath), "utf8");
	written.add(path.resolve(dest));
	console.log(`wrote it/${rel} → ${importPath}`);
}

// Only prune stubs we generated — leave anything hand-edited under it/ alone.
for (const file of listGeneratedAstro(itDir)) {
	if (written.has(path.resolve(file))) continue;
	const text = fs.readFileSync(file, "utf8");
	if (!text.includes("generated by sync-locale-pages")) continue;
	fs.unlinkSync(file);
	console.log(`pruned ${path.relative(pagesDir, file)}`);
}

function pruneEmpty(dir) {
	if (!fs.existsSync(dir)) return;
	for (const name of fs.readdirSync(dir)) {
		const full = path.join(dir, name);
		if (fs.statSync(full).isDirectory()) pruneEmpty(full);
	}
	if (dir !== itDir && fs.readdirSync(dir).length === 0) {
		fs.rmdirSync(dir);
	}
}
pruneEmpty(itDir);

console.log("sync-locale-pages: ok");
